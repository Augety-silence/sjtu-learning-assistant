"""Save a bounded personal calendar snapshot in Downloads, without a dialog."""
from __future__ import annotations
import os
from pathlib import Path


class CalendarExportError(RuntimeError):
    pass


def save_calendar_ics(content, *, directory=None):
    if type(content) is not str or not content.startswith('BEGIN:VCALENDAR\r\n') or not content.endswith('END:VCALENDAR\r\n'):
        raise CalendarExportError('日程导出内容无效。')
    raw = content.encode('utf-8')
    if len(raw) > 2 * 1024 * 1024 or '\0' in content:
        raise CalendarExportError('日程导出内容过大或无效。')
    # Only the fields generated by the personal calendar UI, no attachments,
    # URLs, invites, reminders or arbitrary destination paths.
    allowed = {'BEGIN', 'END', 'VERSION', 'PRODID', 'CALSCALE', 'UID', 'DTSTAMP',
               'SUMMARY', 'DTSTART', 'DTEND', 'LOCATION', 'DESCRIPTION'}
    for line in content.split('\r\n'):
        if any(ord(c) < 32 and c != '\t' for c in line):
            raise CalendarExportError('日程导出内容含无效控制字符。')
        if not line or line.startswith(' '):
            continue
        if line.split(':', 1)[0].split(';', 1)[0] not in allowed:
            raise CalendarExportError('日程导出包含不支持的字段。')
    root = Path(directory) if directory is not None else Path.home() / 'Downloads'
    try:
        root.mkdir(parents=True, exist_ok=True)
        for index in range(1000):
            name = 'SJTU-个人日程' + (f' ({index})' if index else '') + '.ics'
            target = root / name
            try:
                fd = os.open(target, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
            except FileExistsError:
                continue
            try:
                with os.fdopen(fd, 'wb') as stream:
                    stream.write(raw)
                    stream.flush()
                    os.fsync(stream.fileno())
            except BaseException:
                target.unlink(missing_ok=True)
                raise
            return {'filename': name, 'bytes': len(raw), 'destination': 'downloads'}
    except OSError:
        raise CalendarExportError('无法保存日程，请检查下载文件夹的权限或磁盘空间后重试。') from None
    raise CalendarExportError('同名日程文件过多，请整理下载文件夹后重试。')
